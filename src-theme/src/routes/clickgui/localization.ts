export function tCategory(name: string): string {
    return categoryNames[name] ?? name;
}

export function tModule(name: string, spaceSeparated = false): string {
    const translated = moduleNames[name];
    if (translated) {
        return translated;
    }
    if (spaceSeparated) {
        return name.replace(/([a-z0-9])([A-Z])/g, "$1 $2");
    }
    return name;
}
